/**
 * Generates supabase/seed.sql from the same TypeScript seed data the app bundles,
 * so the offline fallback and the database never drift apart.
 *   npm run seed:generate
 */
import { writeFileSync } from 'node:fs'
import { fabrics } from '../src/data/fabrics.ts'
import { suppliers } from '../src/data/suppliers.ts'
import { garments } from '../src/data/garments.ts'
import { courses } from '../src/data/courses.ts'

const q = (v: unknown) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`

const lines: string[] = ['-- Generated by scripts/generate-seed.ts — do not edit by hand.', 'begin;', '']

lines.push('insert into public.suppliers (id, name, country, moq_meters, verified, data) values')
lines.push(suppliers.map((s) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.country)}, ${s.moqMeters}, true, ${j(s)})`).join(',\n'))
lines.push('on conflict (id) do update set name = excluded.name, country = excluded.country, moq_meters = excluded.moq_meters, data = excluded.data;', '')

lines.push('insert into public.fabrics (id, slug, supplier_id, construction, gsm, price_per_meter, sustainability, data) values')
lines.push(fabrics.map((f) => `  (${q(f.id)}, ${q(f.slug)}, ${q(f.supplierId)}, ${q(f.construction)}, ${f.gsm}, ${f.pricePerMeter}, ${f.sustainability}, ${j(f)})`).join(',\n'))
lines.push('on conflict (id) do update set slug = excluded.slug, supplier_id = excluded.supplier_id, construction = excluded.construction, gsm = excluded.gsm, price_per_meter = excluded.price_per_meter, sustainability = excluded.sustainability, data = excluded.data;', '')

lines.push('insert into public.garment_templates (id, data) values')
lines.push(garments.map((g) => `  (${q(g.id)}, ${j(g)})`).join(',\n'))
lines.push('on conflict (id) do update set data = excluded.data;', '')

lines.push('insert into public.courses (id, slug, topic, level, data) values')
lines.push(courses.map((c) => `  (${q(c.id)}, ${q(c.slug)}, ${q(c.topic)}, ${q(c.level)}, ${j(c)})`).join(',\n'))
lines.push('on conflict (id) do update set slug = excluded.slug, topic = excluded.topic, level = excluded.level, data = excluded.data;', '')

lines.push('commit;', '')
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'))
console.log(`seed.sql: ${suppliers.length} suppliers, ${fabrics.length} fabrics, ${garments.length} garments, ${courses.length} courses`)
